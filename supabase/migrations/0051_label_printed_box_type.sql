-- 라벨에 박스 종류를 찍을 때, 출력한 순간 라벨에 찍힌 박스 종류를 기억해 둔다.
--  - box_labels.printed_box_type: 이 라벨을 마지막으로 출력할 때 라벨에 찍힌 박스 종류 이름.
--    null = 박스 종류를 찍지 않고 출력한 라벨(박스 종류 항목이 없는 디자인으로 출력했거나, 이 기능 이전에 출력한 라벨).
--  - 박스 할당을 다시 제출해 박스 종류가 바뀌면 이 값과 지금 제출된 박스 종류를 비교해서 "재출력 필요"를 알려 준다(앱이 계산한다).
--  - 기존 행은 null 그대로 둔다(옛 라벨에는 박스 종류가 찍혀 있지 않으므로 정확하다).
alter table box_labels add column if not exists printed_box_type text;
